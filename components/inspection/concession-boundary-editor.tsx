"use client";

import { useMemo } from "react";
import dynamic from "next/dynamic";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Loader2, Plus, Save, Trash2 } from "lucide-react";
import type { MultiPolygonMapProps } from "@/components/maps/MultiPolygonMap";
import { getPolygonArea, polygonsToGeoJSON } from "@/lib/geoUtils";
import {
  MIN_BOUNDARY_POINTS,
  countUnparseablePoints,
  parseBoundaryPoints,
  type BoundaryPoint,
} from "@/lib/permit/concession-boundary-points";

const MultiPolygonMap = dynamic<MultiPolygonMapProps>(
  () => import("@/components/maps/MultiPolygonMap").then((m) => m.MultiPolygonMap),
  {
    ssr: false,
    loading: () => (
      <div className="flex h-[320px] w-full items-center justify-center rounded-lg border bg-slate-50">
        <span className="text-sm text-slate-400">Loading map…</span>
      </div>
    ),
  }
);

interface ConcessionBoundaryEditorProps {
  points: BoundaryPoint[];
  onPointsChange: (points: BoundaryPoint[]) => void;
  onSave?: (points: BoundaryPoint[]) => Promise<void> | void;
  saving?: boolean;
  readOnly?: boolean;
  inputClassName?: string;
}

/**
 * The assessor's concession boundary: editable coordinate rows plus a live
 * preview of the concession map that will be annexed to the permit.
 *
 * The preview is rendered from the coordinates currently in the boxes — not
 * from anything saved — so the assessor sees the boundary they are recommending
 * take shape as they type. It uses the same MultiPolygonMap renderer as the
 * public permit annex (`components/public/permit-location-map.tsx`), so the
 * approved map is generated by the system from these numbers rather than drawn
 * or attached by hand.
 */
export function ConcessionBoundaryEditor({
  points,
  onPointsChange,
  onSave,
  saving = false,
  readOnly = false,
  inputClassName = "",
}: ConcessionBoundaryEditorProps) {
  const usable = useMemo(() => parseBoundaryPoints(points), [points]);
  const hasDrawablePolygon = usable.length >= MIN_BOUNDARY_POINTS;

  const areaHectares = useMemo(() => {
    if (!hasDrawablePolygon) return null;
    const feature = polygonsToGeoJSON([usable]);
    if (!feature) return null;
    const areaSqMeters = getPolygonArea(feature);
    if (!Number.isFinite(areaSqMeters) || areaSqMeters <= 0) return null;
    return areaSqMeters / 10000;
  }, [usable, hasDrawablePolygon]);

  const invalidCount = countUnparseablePoints(points);

  const updatePoint = (index: number, field: "latitude" | "longitude", value: string) => {
    const next = points.map((point, idx) => (idx === index ? { ...point, [field]: value } : point));
    onPointsChange(next);
  };

  const addPoint = () => {
    onPointsChange([...points, { latitude: "", longitude: "" }]);
  };

  const removePoint = (index: number) => {
    onPointsChange(points.filter((_, idx) => idx !== index));
  };

  const saveDisabled = readOnly || saving || !hasDrawablePolygon || invalidCount > 0;

  return (
    <div className="space-y-4">
      <div>
        <Label>Concession polygon coordinates</Label>
        <div className="space-y-3 mt-2">
          {points.map((point, index) => (
            <div key={index} className="grid grid-cols-12 gap-2 items-center">
              <div className="col-span-2">
                <Label className="text-sm font-medium">Point {index + 1}</Label>
              </div>
              <div className={readOnly ? "col-span-5" : "col-span-4"}>
                <Label className="text-xs text-muted-foreground">Latitude</Label>
                <Input
                  value={point.latitude}
                  onChange={(e) => updatePoint(index, "latitude", e.target.value)}
                  readOnly={readOnly}
                  className={inputClassName}
                />
              </div>
              <div className={readOnly ? "col-span-5" : "col-span-4"}>
                <Label className="text-xs text-muted-foreground">Longitude</Label>
                <Input
                  value={point.longitude}
                  onChange={(e) => updatePoint(index, "longitude", e.target.value)}
                  readOnly={readOnly}
                  className={inputClassName}
                />
              </div>
              {!readOnly && (
                <div className="col-span-2 flex items-end justify-end pt-5">
                  <Button
                    type="button"
                    variant="ghost"
                    size="sm"
                    aria-label={`Remove point ${index + 1}`}
                    disabled={saving || points.length <= MIN_BOUNDARY_POINTS}
                    onClick={() => removePoint(index)}
                  >
                    <Trash2 className="h-4 w-4 text-muted-foreground" />
                  </Button>
                </div>
              )}
            </div>
          ))}
        </div>

        {!readOnly && (
          <div className="mt-3 flex flex-wrap items-center gap-2">
            <Button type="button" size="sm" variant="outline" disabled={saving} onClick={addPoint}>
              <Plus className="h-4 w-4 mr-1.5" />
              Add point
            </Button>
            <Button type="button" size="sm" disabled={saveDisabled} onClick={() => onSave?.(points)}>
              {saving ? (
                <Loader2 className="h-4 w-4 mr-1.5 animate-spin" />
              ) : (
                <Save className="h-4 w-4 mr-1.5" />
              )}
              Save coordinates
            </Button>
            {invalidCount > 0 ? (
              <span className="text-xs text-amber-700">
                {invalidCount} point{invalidCount === 1 ? " has" : "s have"} an incomplete or
                non-numeric coordinate.
              </span>
            ) : !hasDrawablePolygon ? (
              <span className="text-xs text-amber-700">
                At least {MIN_BOUNDARY_POINTS} points are needed to form a concession boundary.
              </span>
            ) : null}
          </div>
        )}
      </div>

      {/* Draft concession map — the annex the permit will carry, generated from
          the coordinates above. */}
      <div className="rounded-lg border bg-slate-50/60 p-3">
        <div className="mb-2 flex flex-wrap items-baseline justify-between gap-2">
          <div>
            <p className="text-sm font-medium">Draft concession map</p>
            <p className="text-xs text-muted-foreground">
              Auto-generated from the coordinates above — this is the map annexed to the permit if
              approved.
            </p>
          </div>
          {areaHectares != null && (
            <span className="text-xs font-medium text-slate-700">
              Boundary area: {areaHectares.toFixed(4)} ha
            </span>
          )}
        </div>

        {hasDrawablePolygon ? (
          <MultiPolygonMap
            polygons={[usable]}
            activePolygonIndex={0}
            height="320px"
            fitAllPolygons
            showMarkersForAll
          />
        ) : (
          <div className="flex h-[320px] w-full items-center justify-center rounded-lg border border-dashed bg-white">
            <span className="px-6 text-center text-sm text-muted-foreground">
              Enter at least {MIN_BOUNDARY_POINTS} valid points to preview the concession map.
            </span>
          </div>
        )}
      </div>
    </div>
  );
}
