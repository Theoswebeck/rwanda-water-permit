// =============================================
// IREMBOPAY API REQUEST/RESPONSE TYPES
// =============================================

export interface IremboPayCustomer {
  email: string;
  phone: string;
  name: string;
}

// Payment Item for IremboPay invoice
export interface IremboPayPaymentItem {
  code: string; // Product/service code (required)
  name: string;
  quantity: number;
  unitAmount: number;
}

export interface IremboPayInitiateRequest {
  transactionId: string; // Unique transaction identifier generated by merchant
  paymentItems: IremboPayPaymentItem[]; // List of products/services
  paymentAccountIdentifier: string; // Payment account where money will be deposited
  expiryAt?: string; // Optional expiry time (ISO 8601 format)
  description?: string; // Optional description
  customer?: IremboPayCustomer; // Optional customer object
  language?: 'EN' | 'FR' | 'RW'; // Optional language
}

export interface IremboPayInitiateResponse {
  success: boolean;
  message?: string;
  data?: {
    payment_ref: string;
    payment_url: string;
    request_id: string;
    amount: number;
    currency: string;
    status: string;
    expires_at?: string;
  };
  error?: {
    code: string;
    message: string;
  };
}

export interface IremboPayWebhookPayload {
  event: WebhookEventType;
  data: {
    reference: string;
    status: string;
    amount: number;
    currency: string;
    transaction_id?: string;
    payment_method?: string;
    payment_channel?: string;
    customer?: {
      email?: string;
      phone?: string;
      name?: string;
    };
    metadata?: Record<string, any>;
    completed_at?: string;
    failed_reason?: string;
  };
  timestamp: string;
  signature?: string;
}

// IremboPay actual API response structure
export interface IremboPayStatusResponse {
  success: boolean;
  message?: string;
  data?: {
    amount: number;
    invoiceNumber: string;
    transactionId: string;
    createdAt: string;
    updatedAt: string;
    description?: string;
    paymentLinkUrl?: string;
    type: string;
    paymentStatus: string; // IremboPay uses: 'NEW', 'PAID', 'FAILED', 'CANCELLED'
    currency: string;
    customer?: {
      fullName?: string;
      email?: string;
      phone?: string;
    };
    createdBy?: string;
    paymentAccountIdentifier?: string;
    paymentItems?: any[];
    paidAt?: string;
    paymentMethod?: string; // e.g., 'MTN_MOMO'
    paymentReference?: string;
  };
  error?: {
    code: string;
    message: string;
  };
}

