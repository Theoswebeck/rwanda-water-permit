export type PaymentStatus = 
  | 'pending' 
  | 'processing' 
  | 'completed' 
  | 'failed' 
  | 'cancelled' 
  | 'refunded';

export type PaymentMethod = 
  | 'mobile_money' 
  | 'card' 
  | 'bank_transfer' 
  | 'ussd' 
  | 'cash';

export type PaymentChannel = 
  | 'mtn_momo'
  | 'airtel_money'
  | 'visa'
  | 'mastercard'
  | 'amex'
  | 'bank_of_kigali'
  | 'equity_bank'
  | 'im_bank'
  | 'cogebanque'
  | 'other';

export type WebhookEventType = 
  | 'payment.initiated'
  | 'payment.processing'
  | 'payment.success'
  | 'payment.failed'
  | 'payment.cancelled'
  | 'payment.refunded';

// =============================================
// MERCHANT CONFIGURATION
// =============================================

export interface Merchant {
  id: string;
  name: string;
  email: string;
  phone?: string;
  
  // IremboPay credentials
  api_key: string;
  public_key?: string;
  
  // Configuration
  callback_url: string;
  success_url?: string;
  failure_url?: string;
  
  // Environment
  is_sandbox: boolean;
  is_active: boolean;
  
  // Audit
  created_at: string;
  updated_at: string;
}

// =============================================
// PAYMENT
// =============================================

export interface Payment {
  id: string;
  
  // References
  application_id: string;
  applicant_id: string;
  merchant_id?: string;
  
  // Payment details
  amount: number;
  currency: string;
  description?: string;
  
  // Status
  status: PaymentStatus;
  payment_method?: PaymentMethod;
  
  // IremboPay fields
  irembo_payment_ref?: string;
  irembo_request_id?: string;
  irembo_transaction_id?: string;
  payment_url?: string;
  
  // Customer details
  customer_email?: string;
  customer_phone?: string;
  customer_name?: string;
  
  // Gateway response
  gateway_response?: Record<string, any>;
  gateway_metadata?: Record<string, any>;
  
  // Timestamps
  initiated_at: string;
  processing_at?: string;
  completed_at?: string;
  failed_at?: string;
  expires_at?: string;
  
  // Audit
  created_at: string;
  updated_at: string;
  created_by?: string;
  
  // Joined relations (from Supabase queries with select joins)
  application?: any; // Application data when joined
  applicant?: any; // User/applicant data when joined
  applications?: any; // Alternative join name
}

