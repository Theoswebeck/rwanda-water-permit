import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const srcDir = path.join(root, "database", "schema-from-supabase");
const outFile = path.join(root, "database", "schema-selfhosted.sql");

async function read(name) {
  return fs.readFile(path.join(srcDir, name), "utf8");
}

function stripHeader(sql) {
  return sql.replace(/^-- =[\s\S]*?\n\n/m, "");
}

function splitFunctionBlocks(sql) {
  return sql
    .split(/(?=CREATE OR REPLACE FUNCTION\s+)/g)
    .map((s) => s.trim())
    .filter((s) => s.startsWith("CREATE OR REPLACE FUNCTION"));
}

function functionNameOf(block) {
  const m = block.match(/^CREATE OR REPLACE FUNCTION\s+([^( \n]+)/i);
  return m?.[1]?.toLowerCase() || "";
}

function cleanFunction(block) {
  let out = block;
  // Remove Supabase auth helper usage in runtime-triggered history functions.
  out = out.replaceAll("auth.uid()", "NULL::uuid");
  return out;
}

function splitStatements(sql) {
  return sql
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
}

function splitViewBlocks(sql) {
  const blocks = [];
  const re = /create or replace view[\s\S]*?(?=create or replace view|$)/gi;
  let m;
  while ((m = re.exec(sql)) !== null) blocks.push(m[0].trim());
  return blocks;
}

async function main() {
  const enums = stripHeader(await read("02-enums.sql"));
  let sequences = stripHeader(await read("03-sequences.sql"));
  let tables = stripHeader(await read("04-tables.sql"));
  let defaults = stripHeader(await read("05-defaults.sql"));
  const constraintsRaw = stripHeader(await read("06-constraints.sql"));
  const indexes = stripHeader(await read("07-indexes.sql"));
  let views = stripHeader(await read("08-views.sql"));
  const functionsSql = stripHeader(await read("09-functions.sql"));
  const triggersSql = stripHeader(await read("10-triggers.sql"));

  // Add self-hosted auth field.
  tables = tables.replace(
    "email character varying(255) not null,",
    "email character varying(255) not null,\n  password_hash text not null,"
  );

  // Sequence ownership can reference tables that do not exist yet in this ordered file.
  // Drop OWNED BY lines to keep first-run ordering safe.
  sequences = sequences
    .split("\n")
    .filter((line) => !/^\s*alter sequence .* owned by /i.test(line))
    .join("\n");

  // Replace Supabase extension-scoped UUID default helper.
  defaults = defaults.replaceAll("extensions.uuid_generate_v4()", "gen_random_uuid()");

  // Keep only app-specific views (drop postgis catalog compatibility views).
  views = splitViewBlocks(views)
    .filter((block) => !/^create or replace view public\.geography_columns as/i.test(block))
    .filter((block) => !/^create or replace view public\.geometry_columns as/i.test(block))
    .join("\n\n");

  // Remove Supabase-coupled functions and clean auth refs in the rest.
  const dropFnNames = new Set([
    "public.sync_user_metadata",
    "public.sync_email_verification",
    "public.enforce_inspection_review_only_update",
  ]);
  const functionBlocks = splitFunctionBlocks(functionsSql)
    .filter((b) => !dropFnNames.has(functionNameOf(b)))
    .map(cleanFunction)
    .map((b) => {
      const trimmed = b.trim();
      return /;\s*$/.test(trimmed) ? trimmed : `${trimmed};`;
    });

  // Remove triggers that depend on removed functions.
  const triggerLines = splitStatements(triggersSql).filter(
    (line) =>
      !line.includes("on_user_update_sync_metadata") &&
      !line.includes("trg_inspections_review_only_update")
  );

  // Ensure referenced UNIQUE/PRIMARY constraints are created before any FKs.
  const constraintLines = splitStatements(constraintsRaw);
  const nonFkConstraints = constraintLines.filter((l) => !/\sFOREIGN KEY\s/i.test(l));
  const fkConstraints = constraintLines.filter((l) => /\sFOREIGN KEY\s/i.test(l));
  const constraints = [...nonFkConstraints, ...fkConstraints].join("\n");

  const lines = [
    "-- Self-hosted schema generated from Supabase export",
    "-- Generated by scripts/build-selfhosted-schema.mjs",
    "begin;",
    "",
    "-- Extensions (minimal self-hosted set)",
    "create extension if not exists pgcrypto;",
    "create extension if not exists postgis;",
    "",
    "-- Enums",
    enums.trim(),
    "",
    "-- Sequences",
    sequences.trim(),
    "",
    "-- Tables",
    tables.trim(),
    "",
    "-- Defaults",
    defaults.trim(),
    "",
    "-- Constraints",
    constraints.trim(),
    "",
    "-- Indexes",
    indexes.trim(),
    "",
    "-- Views",
    views.trim(),
    "",
    "-- Functions",
    functionBlocks.join("\n\n"),
    "",
    "-- Triggers",
    triggerLines.join("\n"),
    "",
    "-- No RLS/policies in self-hosted mode (app-layer authorization)",
    "commit;",
    "",
  ];

  await fs.writeFile(outFile, lines.join("\n"), "utf8");
  console.log(`Wrote ${outFile}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});

