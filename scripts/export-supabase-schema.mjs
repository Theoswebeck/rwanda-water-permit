import fs from "node:fs/promises";
import path from "node:path";

function requireEnv(name) {
  const v = process.env[name];
  if (!v) throw new Error(`Missing env var: ${name}`);
  return v;
}

async function readCursorMcpConfig() {
  const p = path.join(process.env.HOME || "", ".cursor", "mcp.json");
  const raw = await fs.readFile(p, "utf8");
  return { path: p, json: JSON.parse(raw) };
}

function pickMcpServer(mcpJson, serverName = "supabase target") {
  const s = mcpJson?.mcpServers?.[serverName];
  if (!s?.url) throw new Error(`MCP server "${serverName}" not found in ~/.cursor/mcp.json`);
  return { url: s.url, headers: s.headers || {} };
}

class McpClient {
  constructor({ url, headers }) {
    this.url = url;
    this.baseHeaders = headers || {};
    this.sessionId = null;
    this._nextId = 1;
  }

  async rpc(method, params) {
    const id = this._nextId++;
    const headers = {
      "Content-Type": "application/json",
      Accept: "application/json, text/event-stream",
      ...this.baseHeaders,
    };
    if (this.sessionId) headers["Mcp-Session-Id"] = this.sessionId;

    const res = await fetch(this.url, {
      method: "POST",
      headers,
      body: JSON.stringify({ jsonrpc: "2.0", id, method, params: params ?? {} }),
    });

    const text = await res.text();
    let json;
    try {
      json = JSON.parse(text);
    } catch {
      json = { _raw: text };
    }

    if (!res.ok) {
      const msg = json?.error?.message || res.statusText || "MCP request failed";
      throw new Error(`${method} failed (${res.status}): ${msg}`);
    }

    return { res, json };
  }

  async initialize() {
    const { res, json } = await this.rpc("initialize", {
      protocolVersion: "2024-11-05",
      capabilities: {},
      clientInfo: { name: "waterpermit-export", version: "0.0.0" },
    });
    this.sessionId = res.headers.get("mcp-session-id");
    if (!this.sessionId) throw new Error("Missing mcp-session-id header from initialize()");
    return json;
  }

  parseToolContent(toolCallJson) {
    const content = toolCallJson?.result?.content;
    const text = Array.isArray(content) ? content.find((c) => c?.type === "text")?.text : null;
    if (!text) return null;
    // Some tools return JSON (arrays/objects). `execute_sql` often returns a (possibly JSON-stringified) warning string
    // containing an <untrusted-data-...> block that wraps a JSON payload.
    let parsed;
    try {
      parsed = JSON.parse(text);
    } catch {
      parsed = text;
    }

    if (typeof parsed !== "string") return parsed;

    // Supabase wraps SQL results in <untrusted-data-...> tags, and the explanatory text
    // also references the same tag token. Try all tag pairs and return the first JSON payload.
    const matches = parsed.matchAll(/(?:^|\n)<untrusted-data-([^>]+)>\n([\s\S]*?)\n<\/untrusted-data-\1>/gm);
    for (const m of matches) {
      const payload = (m?.[2] || "").trim();
      if (!payload) continue;
      try {
        return JSON.parse(payload);
      } catch {
        // Keep scanning; the first pair in explanatory text is not the payload block.
      }
    }

    // If it's a raw JSON payload with no wrapper, parse it.
    try {
      return JSON.parse(parsed);
    } catch {
      return parsed;
    }
  }

  async toolsCall(name, args) {
    const { json } = await this.rpc("tools/call", { name, arguments: args ?? {} });
    if (json?.error) throw new Error(json.error.message || "tools/call error");
    return this.parseToolContent(json);
  }

  async executeSql(query) {
    const out = await this.toolsCall("execute_sql", { query });
    return out;
  }

  async listTables(schemas = ["public"]) {
    return this.toolsCall("list_tables", { schemas });
  }
}

function sqlQuoteIdent(ident) {
  // Minimal quoting for identifiers. Matches pg_dump behavior sufficiently for our schema.
  if (/^[a-z_][a-z0-9_]*$/.test(ident)) return ident;
  return `"${ident.replace(/"/g, '""')}"`;
}

function sqlLiteral(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

function fmtQualified(schema, name) {
  return `${sqlQuoteIdent(schema)}.${sqlQuoteIdent(name)}`;
}

function joinLines(lines) {
  return lines.filter(Boolean).join("\n") + "\n";
}

async function ensureDir(p) {
  await fs.mkdir(p, { recursive: true });
}

async function writeFileAtomic(filePath, content) {
  const tmp = `${filePath}.tmp`;
  await fs.writeFile(tmp, content, "utf8");
  await fs.rename(tmp, filePath);
}

function header(title) {
  return joinLines([
    "-- =====================================================================",
    `-- ${title}`,
    "-- Generated by scripts/export-supabase-schema.mjs",
    `-- Generated at: ${new Date().toISOString()}`,
    "-- =====================================================================",
    "",
  ]);
}

function normalizeRows(executeSqlResult) {
  // Supabase MCP may return arrays directly, or wrapped objects.
  if (!executeSqlResult) return [];
  if (Array.isArray(executeSqlResult)) return executeSqlResult;
  if (Array.isArray(executeSqlResult.data)) return executeSqlResult.data;
  if (Array.isArray(executeSqlResult.result)) return executeSqlResult.result;
  if (Array.isArray(executeSqlResult.rows)) return executeSqlResult.rows;
  return [];
}

async function main() {
  const outDir = path.join(process.cwd(), "database", "schema-from-supabase");
  await ensureDir(outDir);
  const debug = (...args) => {
    if (process.env.DEBUG_SCHEMA_EXPORT === "1") console.log("[schema-export]", ...args);
  };

  const serverFromEnv = process.env.SUPABASE_MCP_URL && process.env.SUPABASE_MCP_AUTH
    ? { url: requireEnv("SUPABASE_MCP_URL"), headers: { Authorization: requireEnv("SUPABASE_MCP_AUTH") } }
    : null;

  const cursorCfg = serverFromEnv ? null : await readCursorMcpConfig();
  const server = serverFromEnv ? serverFromEnv : pickMcpServer(cursorCfg.json, "supabase target");

  const mcp = new McpClient(server);
  await mcp.initialize();

  // 0) Basic sanity info
  const projectUrl = await mcp.toolsCall("get_project_url", {});
  debug("projectUrl", projectUrl);
  await writeFileAtomic(path.join(outDir, "00-meta.json"), JSON.stringify({ projectUrl }, null, 2) + "\n");

  // 1) Extensions
  const extRaw = await mcp.executeSql(`
    select
      n.nspname as ext_schema,
      e.extname,
      e.extversion
    from pg_extension e
    join pg_namespace n on n.oid = e.extnamespace
    order by 1, 2;
  `);
  debug("extRaw", Array.isArray(extRaw) ? `array(${extRaw.length})` : typeof extRaw);
  if (process.env.DEBUG_SCHEMA_EXPORT === "1" && typeof extRaw === "string") {
    debug("extRawHead", extRaw.slice(0, 220));
  }
  const extRows = normalizeRows(extRaw);
  debug("extensions", extRows.length);
  const extensionsSql = joinLines([
    header("Extensions"),
    ...extRows.map((r) => {
      const schema = r.ext_schema ? `SCHEMA ${sqlQuoteIdent(r.ext_schema)}` : "";
      return `create extension if not exists ${sqlQuoteIdent(r.extname)} ${schema};`;
    }),
    "",
  ]);
  await writeFileAtomic(path.join(outDir, "01-extensions.sql"), extensionsSql);

  // 2) Enums
  const enumRaw = await mcp.executeSql(`
    select
      n.nspname as enum_schema,
      t.typname as enum_name,
      e.enumsortorder,
      e.enumlabel
    from pg_type t
    join pg_namespace n on n.oid = t.typnamespace
    join pg_enum e on e.enumtypid = t.oid
    where n.nspname = 'public'
    order by 1, 2, 3;
  `);
  debug("enumRaw", Array.isArray(enumRaw) ? `array(${enumRaw.length})` : typeof enumRaw);
  if (process.env.DEBUG_SCHEMA_EXPORT === "1" && typeof enumRaw === "string") {
    debug("enumRawHead", enumRaw.slice(0, 220));
  }
  const enumRows = normalizeRows(enumRaw);
  debug("enumRows", enumRows.length);
  const enumsByName = new Map();
  for (const r of enumRows) {
    const key = `${r.enum_schema}.${r.enum_name}`;
    const arr = enumsByName.get(key) || [];
    arr.push(r.enumlabel);
    enumsByName.set(key, arr);
  }
  const enumsSqlParts = [header("Enums")];
  for (const [k, labels] of [...enumsByName.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    const [schema, name] = k.split(".");
    const vals = labels.map(sqlLiteral).join(", ");
    enumsSqlParts.push(`do $$ begin`);
    enumsSqlParts.push(`  create type ${fmtQualified(schema, name)} as enum (${vals});`);
    enumsSqlParts.push(`exception when duplicate_object then null; end $$;`);
    enumsSqlParts.push("");
  }
  await writeFileAtomic(path.join(outDir, "02-enums.sql"), joinLines(enumsSqlParts));

  // 3) Sequences
  const seqRaw = await mcp.executeSql(`
    select
      schemaname,
      sequencename,
      data_type,
      start_value,
      min_value,
      max_value,
      increment_by,
      cycle,
      cache_size
    from pg_sequences
    where schemaname = 'public'
    order by 1, 2;
  `);
  debug("seqRaw", Array.isArray(seqRaw) ? `array(${seqRaw.length})` : typeof seqRaw);
  if (process.env.DEBUG_SCHEMA_EXPORT === "1" && typeof seqRaw === "string") {
    debug("seqRawHead", seqRaw.slice(0, 220));
  }
  const seqRows = normalizeRows(seqRaw);
  debug("sequences", seqRows.length);

  const seqOwnedRows = normalizeRows(await mcp.executeSql(`
    select
      ns.nspname as sequence_schema,
      seq.relname as sequence_name,
      nt.nspname as table_schema,
      tbl.relname as table_name,
      a.attname as column_name
    from pg_class seq
    join pg_namespace ns on ns.oid = seq.relnamespace
    left join pg_depend dep on dep.objid = seq.oid and dep.deptype = 'a'
    left join pg_class tbl on tbl.oid = dep.refobjid
    left join pg_namespace nt on nt.oid = tbl.relnamespace
    left join pg_attribute a on a.attrelid = tbl.oid and a.attnum = dep.refobjsubid
    where seq.relkind = 'S'
      and ns.nspname = 'public'
    order by 1, 2;
  `));
  const ownedBy = new Map(); // key: schema.seq -> {table_schema, table_name, column_name}
  for (const r of seqOwnedRows) {
    if (r.table_schema && r.table_name && r.column_name) {
      ownedBy.set(`${r.sequence_schema}.${r.sequence_name}`, r);
    }
  }

  const seqSqlParts = [header("Sequences")];
  for (const r of seqRows) {
    const qn = fmtQualified(r.schemaname, r.sequencename);
    const cycle = r.cycle ? "CYCLE" : "NO CYCLE";
    seqSqlParts.push(`create sequence if not exists ${qn}`);
    seqSqlParts.push(`  as ${r.data_type}`);
    seqSqlParts.push(`  increment by ${r.increment_by}`);
    seqSqlParts.push(`  minvalue ${r.min_value}`);
    seqSqlParts.push(`  maxvalue ${r.max_value}`);
    seqSqlParts.push(`  start with ${r.start_value}`);
    seqSqlParts.push(`  cache ${r.cache_size}`);
    seqSqlParts.push(`  ${cycle};`);
    const ob = ownedBy.get(`${r.schemaname}.${r.sequencename}`);
    if (ob) {
      seqSqlParts.push(`alter sequence ${qn} owned by ${fmtQualified(ob.table_schema, ob.table_name)}.${sqlQuoteIdent(ob.column_name)};`);
    }
    seqSqlParts.push("");
  }
  await writeFileAtomic(path.join(outDir, "03-sequences.sql"), joinLines(seqSqlParts));

  // 4) Tables + column defaults collected separately (so sequences exist first)
  const tablesRaw = await mcp.listTables(["public"]);
  const tables = Array.isArray(tablesRaw) ? tablesRaw : tablesRaw?.data || [];
  debug("tables", tables.length);
  const tableNames = tables
    .map((t) => ({ schema: t.schema || "public", name: t.name || t.table_name || t.tableName }))
    .filter((t) => t.schema && t.name);

  const tableSqlParts = [header("Tables (without constraints)")];
  const defaultSqlParts = [header("Column defaults")];
  for (const t of tableNames.sort((a, b) => `${a.schema}.${a.name}`.localeCompare(`${b.schema}.${b.name}`))) {
    const cols = normalizeRows(await mcp.executeSql(`
      select
        a.attname as column_name,
        format_type(a.atttypid, a.atttypmod) as column_type,
        a.attnotnull as not_null,
        a.attidentity as identity,
        a.attgenerated as generated,
        col.collcollate as collation,
        pg_get_expr(ad.adbin, ad.adrelid) as default_expr
      from pg_attribute a
      join pg_class c on c.oid = a.attrelid
      join pg_namespace n on n.oid = c.relnamespace
      left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
      left join pg_collation col on col.oid = a.attcollation and a.attcollation <> (select typcollation from pg_type where oid = a.atttypid)
      where n.nspname = ${sqlLiteral(t.schema)}
        and c.relname = ${sqlLiteral(t.name)}
        and a.attnum > 0
        and not a.attisdropped
      order by a.attnum;
    `));

    const qTable = fmtQualified(t.schema, t.name);
    tableSqlParts.push(`create table if not exists ${qTable} (`);
    const colLines = [];
    for (const c of cols) {
      const colName = sqlQuoteIdent(c.column_name);
      let line = `  ${colName} ${c.column_type}`;
      if (c.collation) line += ` collate ${sqlQuoteIdent(c.collation)}`;
      if (c.generated === "s") {
        // stored generated; expression lives in default_expr for generated columns on some versions, but not reliably.
        // Keep as-is (fallback) by omitting and letting follow-up fixes happen manually if any.
      }
      if (c.identity === "a") line += ` generated always as identity`;
      if (c.identity === "d") line += ` generated by default as identity`;
      // defaults: emit later to ensure sequences exist and to keep table DDL clean
      if (c.not_null) line += ` not null`;
      colLines.push(line);

      if (c.default_expr && !String(c.default_expr).includes("nextval(")) {
        defaultSqlParts.push(`alter table ${qTable} alter column ${colName} set default ${c.default_expr};`);
      } else if (c.default_expr && String(c.default_expr).includes("nextval(")) {
        defaultSqlParts.push(`alter table ${qTable} alter column ${colName} set default ${c.default_expr};`);
      }
    }
    tableSqlParts.push(colLines.join(",\n"));
    tableSqlParts.push(");");
    tableSqlParts.push("");
  }
  await writeFileAtomic(path.join(outDir, "04-tables.sql"), joinLines(tableSqlParts));
  await writeFileAtomic(path.join(outDir, "05-defaults.sql"), joinLines(defaultSqlParts));

  // 5) Constraints (PK/UNIQUE/CHECK/FK)
  const constraintsSqlParts = [header("Table constraints")];
  for (const t of tableNames.sort((a, b) => `${a.schema}.${a.name}`.localeCompare(`${b.schema}.${b.name}`))) {
    const qTable = fmtQualified(t.schema, t.name);
    const cons = normalizeRows(await mcp.executeSql(`
      select
        conname,
        contype,
        pg_get_constraintdef(oid, true) as def
      from pg_constraint
      where conrelid = ${sqlLiteral(`${t.schema}.${t.name}`)}::regclass
      order by
        case contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'f' then 4 else 10 end,
        conname;
    `));
    for (const c of cons) {
      constraintsSqlParts.push(`alter table ${qTable} add constraint ${sqlQuoteIdent(c.conname)} ${c.def};`);
    }
    if (cons.length) constraintsSqlParts.push("");
  }
  await writeFileAtomic(path.join(outDir, "06-constraints.sql"), joinLines(constraintsSqlParts));

  // 6) Indexes (excluding those backing constraints)
  const indexesSqlParts = [header("Indexes (excluding constraint-backed indexes)")];
  for (const t of tableNames.sort((a, b) => `${a.schema}.${a.name}`.localeCompare(`${b.schema}.${b.name}`))) {
    const idx = normalizeRows(await mcp.executeSql(`
      select
        pg_get_indexdef(i.indexrelid) as indexdef
      from pg_index i
      join pg_class ic on ic.oid = i.indexrelid
      left join pg_constraint con on con.conindid = i.indexrelid
      where i.indrelid = ${sqlLiteral(`${t.schema}.${t.name}`)}::regclass
        and con.oid is null
      order by ic.relname;
    `));
    for (const r of idx) {
      indexesSqlParts.push(`${r.indexdef};`);
    }
    if (idx.length) indexesSqlParts.push("");
  }
  await writeFileAtomic(path.join(outDir, "07-indexes.sql"), joinLines(indexesSqlParts));

  // 7) Views
  const viewRows = normalizeRows(await mcp.executeSql(`
    select table_schema, table_name
    from information_schema.views
    where table_schema = 'public'
    order by 1, 2;
  `));
  const viewsSqlParts = [header("Views")];
  for (const v of viewRows) {
    const qView = fmtQualified(v.table_schema, v.table_name);
    const defRows = normalizeRows(await mcp.executeSql(`select pg_get_viewdef(${sqlLiteral(`${v.table_schema}.${v.table_name}`)}::regclass, true) as def;`));
    const def = defRows[0]?.def;
    if (def) {
      viewsSqlParts.push(`create or replace view ${qView} as`);
      viewsSqlParts.push(def.trim().replace(/;$/, "") + ";");
      viewsSqlParts.push("");
    }
  }
  await writeFileAtomic(path.join(outDir, "08-views.sql"), joinLines(viewsSqlParts));

  // 8) Functions (public schema only, excluding extension-owned functions to keep payload manageable)
  const fnRows = normalizeRows(await mcp.executeSql(`
    select p.oid, pg_get_functiondef(p.oid) as def
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    left join pg_depend d on d.objid = p.oid and d.deptype = 'e'
    where n.nspname = 'public'
      and d.objid is null
    order by p.proname, p.oid;
  `));
  const functionsSql = joinLines([
    header("Functions"),
    ...fnRows.map((r) => (r.def ? String(r.def).trim().replace(/\\s+$/, "") + "\n" : "")),
    "",
  ]);
  await writeFileAtomic(path.join(outDir, "09-functions.sql"), functionsSql);

  // 9) Triggers (user-defined)
  const trgRows = normalizeRows(await mcp.executeSql(`
    select
      n.nspname as table_schema,
      c.relname as table_name,
      t.tgname,
      pg_get_triggerdef(t.oid, true) as def
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and not t.tgisinternal
    order by 1, 2, 3;
  `));
  const triggersSql = joinLines([
    header("Triggers"),
    ...trgRows.map((r) => (r.def ? String(r.def).trim().replace(/;$/, "") + ";" : "")),
    "",
  ]);
  await writeFileAtomic(path.join(outDir, "10-triggers.sql"), triggersSql);

  // 10) RLS + Policies (for reference; we’ll strip these for self-hosted)
  const rlsTables = normalizeRows(await mcp.executeSql(`
    select n.nspname as table_schema, c.relname as table_name, c.relrowsecurity as rls_enabled, c.relforcerowsecurity as rls_forced
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relkind = 'r'
    order by 1, 2;
  `));
  const policyRows = normalizeRows(await mcp.executeSql(`
    select schemaname, tablename, policyname, permissive, roles, cmd, qual, with_check
    from pg_policies
    where schemaname = 'public'
    order by schemaname, tablename, policyname;
  `));

  const policiesSqlParts = [header("RLS & Policies (Supabase-specific; remove for self-hosted)")];
  for (const t of rlsTables) {
    if (t.rls_enabled) {
      policiesSqlParts.push(`alter table ${fmtQualified(t.table_schema, t.table_name)} enable row level security;`);
    }
    if (t.rls_forced) {
      policiesSqlParts.push(`alter table ${fmtQualified(t.table_schema, t.table_name)} force row level security;`);
    }
  }
  if (rlsTables.some((t) => t.rls_enabled || t.rls_forced)) policiesSqlParts.push("");

  for (const p of policyRows) {
    const qTable = fmtQualified(p.schemaname, p.tablename);
    const permissive = p.permissive ? "permissive" : "restrictive";
    const roles = Array.isArray(p.roles) ? p.roles : null;
    const rolesSql = roles && roles.length ? `to ${roles.map(sqlQuoteIdent).join(", ")}` : "to public";
    const qual = p.qual ? ` using (${p.qual})` : "";
    const withCheck = p.with_check ? ` with check (${p.with_check})` : "";
    policiesSqlParts.push(
      `create policy ${sqlQuoteIdent(p.policyname)} on ${qTable} as ${permissive} for ${p.cmd} ${rolesSql}${qual}${withCheck};`
    );
  }
  policiesSqlParts.push("");
  await writeFileAtomic(path.join(outDir, "11-rls-policies.sql"), joinLines(policiesSqlParts));

  // 11) Combined file in correct-ish order
  const order = [
    "01-extensions.sql",
    "02-enums.sql",
    "03-sequences.sql",
    "04-tables.sql",
    "05-defaults.sql",
    "06-constraints.sql",
    "07-indexes.sql",
    "08-views.sql",
    "09-functions.sql",
    "10-triggers.sql",
    "11-rls-policies.sql",
  ];

  const combinedParts = [header("Combined schema-from-supabase.sql")];
  for (const f of order) {
    const c = await fs.readFile(path.join(outDir, f), "utf8");
    combinedParts.push(`-- >>> BEGIN ${f}`);
    combinedParts.push(c.trimEnd());
    combinedParts.push(`-- <<< END ${f}`);
    combinedParts.push("");
  }

  await writeFileAtomic(path.join(process.cwd(), "database", "schema-from-supabase.sql"), joinLines(combinedParts));

  console.log(`Wrote schema export to ${outDir} and database/schema-from-supabase.sql`);
}

main().catch((e) => {
  console.error(e?.stack || String(e));
  process.exit(1);
});

