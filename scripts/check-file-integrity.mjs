#!/usr/bin/env node
/**
 * Upload integrity checker — does every file the database references still
 * exist on disk?
 *
 * This exists because two separate document losses went unnoticed for months.
 * On 2026-07-08 a `git clean -fd` against the production checkout deleted
 * `public/uploads`, taking 1,400 applicant documents AND all 2,703
 * permit-registry documents. The applicant files were noticed within days; the
 * registry files were not found until 2026-09-22, because the recovery work
 * enumerated the `documents` table and nothing else.
 *
 * So this script does NOT hardcode a list of tables. It asks the database
 * which columns look like file paths, then checks every value that points into
 * `/uploads/`. A table added next year is covered without anyone remembering
 * to update this file — that forgetting is the failure mode it guards against.
 *
 * Baseline: some files are genuinely unrecoverable (12 applicant documents
 * uploaded between the 8-July backup and the deletion). Alerting on those every
 * night would train people to ignore the alert, so known-missing paths live in
 * a baseline file and only NEW disappearances send mail.
 *
 *   node scripts/check-file-integrity.mjs              # check, mail if new losses
 *   node scripts/check-file-integrity.mjs --baseline   # accept current misses as known
 *   node scripts/check-file-integrity.mjs --no-email   # report only
 *
 * Exit codes:
 *   0 -> every referenced file is present (or already baselined)
 *   1 -> new missing files detected
 *   2 -> infrastructure problem (no DATABASE_URL, connection failed, ...)
 */

import { access, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";
import pg from "pg";
import nodemailer from "nodemailer";
import dotenv from "dotenv";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP_DIR = path.resolve(HERE, "..");
const PUBLIC_DIR = path.join(APP_DIR, "public");

// On the server env lives in .env.production; .env holds a couple of overrides.
// dotenv keeps the first value it sees, so load the more specific file first.
dotenv.config({ path: path.join(APP_DIR, ".env.production") });
dotenv.config({ path: path.join(APP_DIR, ".env") });

const BASELINE_PATH =
  process.env.INTEGRITY_BASELINE_PATH || "/var/data/waterpermit/known-missing.txt";
const ALERT_TO = process.env.INTEGRITY_ALERT_TO || process.env.SUPPORT_EMAIL || "info@rwb.rw";

const args = new Set(process.argv.slice(2));
const WRITE_BASELINE = args.has("--baseline");
const NO_EMAIL = args.has("--no-email");

/**
 * Columns whose *name* suggests a file reference. The name is only a shortlist —
 * the authoritative filter is the `/uploads/` prefix on the value itself, which
 * is what separates a stored upload from an external callback URL.
 */
const CANDIDATE_COLUMNS_SQL = `
  select table_name, column_name
  from information_schema.columns
  where table_schema = 'public'
    and data_type in ('text', 'character varying')
    and column_name ~* '(path|file|url)'
  order by table_name, column_name
`;

export async function fileExists(relPath) {
  // Paths are stored as "/uploads/...". Refuse anything that tries to climb out
  // of public/ rather than silently stat'ing an arbitrary file.
  const rel = relPath.replace(/^\/+/, "");
  const resolved = path.resolve(PUBLIC_DIR, rel);
  if (!resolved.startsWith(PUBLIC_DIR + path.sep)) return false;
  try {
    await access(resolved);
    return true;
  } catch {
    return false;
  }
}

async function loadBaseline() {
  try {
    const raw = await readFile(BASELINE_PATH, "utf8");
    return new Set(
      raw
        .split("\n")
        .map((line) => line.trim())
        .filter((line) => line && !line.startsWith("#"))
    );
  } catch {
    return new Set();
  }
}

async function saveBaseline(paths) {
  await mkdir(path.dirname(BASELINE_PATH), { recursive: true });
  const header =
    "# Known-unrecoverable upload paths. Generated by scripts/check-file-integrity.mjs --baseline.\n" +
    "# These are NOT alerted on. Remove a line once the file is restored.\n" +
    `# Last written: ${new Date().toISOString()}\n`;
  await writeFile(BASELINE_PATH, header + [...paths].sort().join("\n") + "\n", "utf8");
}

async function sendAlert(subject, body) {
  const user = process.env.SMTP_USER;
  const pass = process.env.SMTP_PASS;
  if (!user || !pass) {
    console.error("SMTP not configured - skipping email alert.");
    return;
  }
  const transporter = nodemailer.createTransport({
    host: process.env.SMTP_HOST || "smtp.gmail.com",
    port: parseInt(process.env.SMTP_PORT || "587", 10),
    secure: false,
    auth: { user, pass },
  });
  await transporter.sendMail({
    from: process.env.EMAIL_FROM || user,
    to: ALERT_TO,
    subject,
    text: body,
  });
  console.log(`Alert emailed to ${ALERT_TO}`);
}

async function main() {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    console.error("DATABASE_URL is not set.");
    process.exit(2);
  }

  const client = new pg.Client({ connectionString });
  await client.connect();
  // Nothing here should ever write to the database.
  await client.query("set default_transaction_read_only = on");

  const { rows: columns } = await client.query(CANDIDATE_COLUMNS_SQL);

  const missingBySource = new Map();
  let checked = 0;

  for (const { table_name: table, column_name: column } of columns) {
    const { rows } = await client.query(
      `select distinct "${column}" as p from "${table}" where "${column}" like '/uploads/%'`
    );
    if (!rows.length) continue;

    for (const { p } of rows) {
      checked += 1;
      if (await fileExists(p)) continue;
      const source = `${table}.${column}`;
      if (!missingBySource.has(source)) missingBySource.set(source, []);
      missingBySource.get(source).push(p);
    }
  }

  await client.end();

  const allMissing = [...missingBySource.values()].flat();

  if (WRITE_BASELINE) {
    await saveBaseline(allMissing);
    console.log(`Baseline written: ${allMissing.length} known-missing paths -> ${BASELINE_PATH}`);
    return 0;
  }

  const baseline = await loadBaseline();
  const newlyMissing = allMissing.filter((p) => !baseline.has(p));

  console.log(`Checked ${checked} referenced files across ${columns.length} candidate columns.`);
  console.log(`Missing: ${allMissing.length} (known/baselined: ${allMissing.length - newlyMissing.length}, new: ${newlyMissing.length})`);

  if (!newlyMissing.length) return 0;

  const bySource = [...missingBySource.entries()]
    .map(([source, paths]) => {
      const fresh = paths.filter((p) => !baseline.has(p));
      return fresh.length ? `${source}: ${fresh.length} missing\n${fresh.slice(0, 20).map((p) => `  ${p}`).join("\n")}${fresh.length > 20 ? `\n  ... and ${fresh.length - 20} more` : ""}` : null;
    })
    .filter(Boolean)
    .join("\n\n");

  const body =
    `${newlyMissing.length} file(s) referenced by the database are no longer on disk.\n\n` +
    `Server: ${process.env.NEXT_PUBLIC_APP_URL || "waterpermit"}\n` +
    `Checked: ${checked} referenced files\n` +
    `Detected: ${new Date().toISOString()}\n\n` +
    `${bySource}\n\n` +
    `Investigate before the next nightly backup rotates (retention is finite).\n` +
    `If these are genuinely unrecoverable, baseline them:\n` +
    `  node /opt/waterpermit/app/scripts/check-file-integrity.mjs --baseline\n`;

  console.error(body);
  if (!NO_EMAIL) {
    await sendAlert(`[Water Permit] ${newlyMissing.length} uploaded file(s) missing from disk`, body);
  }
  return 1;
}

// Only run when executed directly, so the self-check can import fileExists.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main()
    .then((code) => process.exit(code))
    .catch((error) => {
      console.error("File integrity check failed:", error);
      process.exit(2);
    });
}
