#!/usr/bin/env node
// Local development setup — runs automatically before `npm run dev`.
//
//   npm run dev   first run: creates .env.local, downloads PostgreSQL 14 + PostGIS (Windows)
//                 into .localdb/ and creates an empty database from database/schema-prod.sql.
//                 Later runs reuse it — everything created locally is kept (.localdb/data).
//                 Start over: delete .localdb/data.
//
// Windows: everything is portable inside .localdb/ — no installer, no admin rights.
// macOS:   uses Postgres.app (https://postgresapp.com, v14) if installed.
// Linux:   set PG_BIN to a PostgreSQL 14 bin folder that has PostGIS.
// Fully offline: nothing is read from or written to the RWB server.

import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync, cpSync, rmSync, readdirSync, createWriteStream } from 'node:fs'
import { randomBytes } from 'node:crypto'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Readable } from 'node:stream'
import { pipeline } from 'node:stream/promises'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const LOCAL = join(ROOT, '.localdb')
const ENV_FILE = join(ROOT, '.env.local')
const IS_WIN = process.platform === 'win32'
const EXE = IS_WIN ? '.exe' : ''

const PG_ZIP = 'https://get.enterprisedb.com/postgresql/postgresql-14.23-1-windows-x64-binaries.zip'
const POSTGIS_ZIP = 'https://download.osgeo.org/postgis/windows/pg14/postgis-bundle-pg14-3.6.1x64.zip'

const APP_USER = 'waterpermit_app'
const APP_PASSWORD = 'local-dev-only'
const LOCAL_URL = `postgresql://${APP_USER}:${APP_PASSWORD}@127.0.0.1:5433/waterpermit` // 5433: 5432 is often taken by an installed PostgreSQL

const log = (msg) => console.log(`[dev-db] ${msg}`)
function fail(msg) {
  console.error(`[dev-db] ${msg}`)
  process.exit(1)
}

function run(cmd, args, { env, allowFail = false, quiet = false } = {}) {
  const r = spawnSync(cmd, args, { env: { ...process.env, ...env }, encoding: 'utf8', stdio: quiet ? 'pipe' : ['ignore', 'pipe', 'pipe'] })
  if (r.error) fail(`${cmd}: ${r.error.message}`)
  if (r.status !== 0 && !allowFail) fail(`${cmd} ${args.join(' ')} failed:\n${r.stderr || r.stdout}`)
  return r
}

// ---------------------------------------------------------------- .env.local
function ensureEnvFile() {
  if (existsSync(ENV_FILE)) return
  log('creating .env.local with local-only settings')
  writeFileSync(
    ENV_FILE,
    [
      '# Local development — generated by scripts/dev-db.mjs. Never deploy this file.',
      `DATABASE_URL=${LOCAL_URL}`,
      `AUTH_JWT_SECRET=${randomBytes(32).toString('hex')}`,
      'NEXT_PUBLIC_APP_URL=http://localhost:3000',
      'TZ=Africa/Kigali',
      '# Open every page without signing in (localhost + npm run dev only) — lib/auth/dev-bypass.ts',
      'DEV_AUTH_BYPASS=true',
      '# DEV_AUTH_EMAIL=someone@rwb.rw',
      '# No real SMS or email from a local copy of real user data:',
      'PINDO_DEVELOPMENT_MODE=true',
      'NEXT_PUBLIC_PAYMENT_DEMO_MODE=true',
      'PAYMENT_DEMO_MODE=true',
      'NEXT_PUBLIC_APPLICATION_FEE=20',
      '',
    ].join('\n')
  )
}

function envValue(key) {
  const line = readFileSync(ENV_FILE, 'utf8').split(/\r?\n/).filter((l) => l.startsWith(`${key}=`)).pop()
  return line ? line.slice(key.length + 1).trim() : ''
}

// ---------------------------------------------------------------- PostgreSQL binaries
async function download(url, dest) {
  log(`downloading ${url.split('/').pop()} …`)
  const res = await fetch(url)
  if (!res.ok) fail(`download failed (${res.status}): ${url}`)
  await pipeline(Readable.fromWeb(res.body), createWriteStream(dest))
}

async function ensureWindowsPostgres() {
  const pgsql = join(LOCAL, 'pgsql')
  const bin = join(pgsql, 'bin')
  if (existsSync(join(pgsql, 'share', 'extension', 'postgis.control'))) return bin

  mkdirSync(LOCAL, { recursive: true })
  const pgZip = join(LOCAL, 'postgresql.zip')
  const gisZip = join(LOCAL, 'postgis.zip')
  await download(PG_ZIP, pgZip)
  await download(POSTGIS_ZIP, gisZip)

  log('extracting PostgreSQL …')
  rmSync(pgsql, { recursive: true, force: true })
  run('tar', ['-xf', pgZip, '-C', LOCAL]) // Windows 10+ ships bsdtar, which reads .zip
  log('extracting PostGIS …')
  const gisTmp = join(LOCAL, 'postgis-tmp')
  rmSync(gisTmp, { recursive: true, force: true })
  mkdirSync(gisTmp)
  run('tar', ['-xf', gisZip, '-C', gisTmp])
  const bundle = join(gisTmp, readdirSync(gisTmp).find((d) => d.startsWith('postgis-bundle')))
  for (const dir of ['bin', 'lib', 'share', 'gdal-data']) {
    if (existsSync(join(bundle, dir))) cpSync(join(bundle, dir), join(pgsql, dir), { recursive: true })
  }
  rmSync(gisTmp, { recursive: true, force: true })
  rmSync(pgZip, { force: true })
  rmSync(gisZip, { force: true })
  return bin
}

async function pgBin() {
  if (process.env.PG_BIN) return process.env.PG_BIN
  if (IS_WIN) return ensureWindowsPostgres()
  const mac = '/Applications/Postgres.app/Contents/Versions/14/bin'
  if (existsSync(join(mac, 'pg_ctl'))) return mac
  fail('PostgreSQL 14 not found. macOS: install Postgres.app. Linux: set PG_BIN to a PostgreSQL 14 bin folder (with PostGIS).')
}

// ---------------------------------------------------------------- database
function grantApp(psql, user) {
  psql('waterpermit', `grant usage, create on schema public to "${user}";
    grant all on all tables in schema public to "${user}";
    grant all on all sequences in schema public to "${user}";
    grant execute on all functions in schema public to "${user}"`)
}

async function main() {
  ensureEnvFile()
  const url = envValue('DATABASE_URL')
  // Password of the local `postgres` superuser, if one was set (default: none, trust auth).
  if (envValue('PGPASSWORD')) process.env.PGPASSWORD = envValue('PGPASSWORD')
  const port = url.match(/@(?:127\.0\.0\.1|localhost):(\d+)\//)?.[1]
  if (!port) {
    log('DATABASE_URL in .env.local is not a local database — leaving it alone.')
    return
  }

  const bin = await pgBin()
  const tool = (name) => join(bin, name + EXE)
  const psql = (db, sql, opts) =>
    run(tool('psql'), ['-h', '127.0.0.1', '-p', port, '-U', 'postgres', '-d', db, '-v', 'ON_ERROR_STOP=1', '-qtAc', sql], opts)

  const ready = run(tool('pg_isready'), ['-q', '-h', '127.0.0.1', '-p', port], { allowFail: true, quiet: true }).status === 0
  if (!ready) {
    const data = join(LOCAL, 'data')
    if (!existsSync(join(data, 'PG_VERSION'))) {
      log('creating local database cluster in .localdb/data')
      mkdirSync(data, { recursive: true })
      run(tool('initdb'), ['-D', data, '-U', 'postgres', '--auth=trust', '--encoding=UTF8', '--locale=C'])
    }
    log(`starting PostgreSQL on 127.0.0.1:${port}`)
    // stdio 'ignore': on Windows the server inherits piped handles and spawnSync would wait on it forever.
    const started = spawnSync(tool('pg_ctl'), ['-D', data, '-l', join(LOCAL, 'postgres.log'), '-o', `-p ${port} -c listen_addresses=127.0.0.1`, '-w', 'start'], { stdio: 'ignore' })
    if (started.status !== 0) fail(`PostgreSQL did not start — see ${join(LOCAL, 'postgres.log')}`)
  } else if (run(tool('psql'), ['-w', '-h', '127.0.0.1', '-p', port, '-U', 'postgres', '-d', 'postgres', '-c', 'select 1'], { allowFail: true, quiet: true }).status !== 0) {
    fail(`cannot sign in to PostgreSQL on port ${port}. If you set a postgres password, put it in .env.local as PGPASSWORD=...; otherwise another PostgreSQL uses this port — pick a free one in DATABASE_URL (e.g. :5434).`)
  }

  // The app connects with whatever user/password is in DATABASE_URL.
  const m = url.match(/^postgres(?:ql)?:\/\/([^:]+):(.*)@(?:127\.0\.0\.1|localhost):\d+\//)
  const [user, password] = m ? [decodeURIComponent(m[1]), decodeURIComponent(m[2])] : [APP_USER, APP_PASSWORD]
  const lit = (s) => `'${s.replace(/'/g, "''")}'`
  const hasRole = psql('postgres', `select 1 from pg_roles where rolname=${lit(user)}`).stdout.trim() === '1'
  psql('postgres', `${hasRole ? 'alter' : 'create'} role "${user}" login password ${lit(password)}`)

  const hasDb = psql('postgres', `select 1 from pg_database where datname='waterpermit'`).stdout.trim() === '1'
  if (!hasDb) psql('postgres', `create database waterpermit owner "${user}"`)
  const tables = psql('waterpermit', `select count(*) from pg_tables where schemaname='public'`).stdout.trim()
  if (tables === '0') {
    log('creating an EMPTY local database from database/schema-prod.sql')
    for (const ext of ['postgis', 'pgcrypto', '"uuid-ossp"']) psql('waterpermit', `create extension if not exists ${ext}`)
    run(tool('psql'), ['-h', '127.0.0.1', '-p', port, '-U', 'postgres', '-d', 'waterpermit', '-q', '-f', join(ROOT, 'database', 'schema-prod.sql')], { quiet: true })
  }
  grantApp(psql, user)
  psql('waterpermit', `insert into public.users (email, role, status, account_type, first_name, last_name, password_hash)
    values ('admin@localhost', 'admin', 'active', 'individual', 'Local', 'Admin', 'local-dev-no-login')
    on conflict do nothing`)
  const users = psql('waterpermit', 'select count(*) from public.users').stdout.trim()
  log(`local database ready (${users} users) — data is kept between runs`)
}

main().catch((err) => fail(err.stack || String(err)))
